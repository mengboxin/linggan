const DICT: Record<Lang, Record<I18nKey, string>> = { zh: ZH, en: EN }

interface I18nState {
  lang: Lang
  setLang: (l: Lang) => void
  toggle: () => void
}

export const useI18nStore = create<I18nState>((set, get) => ({
  lang: (localStorage.getItem(STORAGE_KEY) as Lang) ?? 'zh',
  setLang: (lang) => {
    localStorage.setItem(STORAGE_KEY, lang)
    set({ lang })
  },
  toggle: () => get().setLang(get().lang === 'zh' ? 'en' : 'zh'),
}))

/** 在组件外使用（非响应式） */
export function t(key: I18nKey): string {
  const lang = (localStorage.getItem(STORAGE_KEY) as Lang) ?? 'zh'
  return DICT[lang][key]
}

/** 在组件内使用（响应式） */
export function useT() {
  const { lang } = useI18nStore()
  return (key: I18nKey) => DICT[lang][key]
}
